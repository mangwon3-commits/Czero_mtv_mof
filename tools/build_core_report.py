def setfont(run, size=BODY, bold=False):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    run._element.rPr.rFonts.set(qn('w:ascii'), FONT)
    run._element.rPr.rFonts.set(qn('w:hAnsi'), FONT)


def clear_cell(cell):
    """셀을 완전히 비운다 (문단 + 표). 양식 표는 미리 떠서 재사용한다."""
    for tb in list(cell.tables):
        tb._element.getparent().remove(tb._element)
    for p in cell.paragraphs[1:]:
        p._element.getparent().remove(p._element)
    p = cell.paragraphs[0]
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    return p


def para(cell, first=None):
    if first is not None:
        p = first
    else:
        p = cell.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    pf.space_after = Pt(2)
    pf.space_before = Pt(0)
    return p


def txt(cell, chunks, size=BODY, align=None, indent=None, space_after=2,
        space_before=0, first=None):
    """chunks: 문자열 또는 [(글자, 굵기), ...]"""
    p = para(cell, first)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    if indent is not None:
        p.paragraph_format.left_indent = Cm(indent)
    p.alignment = align if align else WD_ALIGN_PARAGRAPH.JUSTIFY
    if isinstance(chunks, str):
        chunks = [(chunks, False)]
    for s, b in chunks:
        setfont(p.add_run(s), size, b)
    return p


def h(cell, text, size=11, space_before=5):
    return txt(cell, [(text, True)], size=size, align=WD_ALIGN_PARAGRAPH.LEFT,
               space_before=space_before, space_after=2)


def fig(cell, name, caption, width=11.4):
    p = para(cell)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(3)
    p.paragraph_format.space_after = Pt(1)
    p.add_run().add_picture(FIG + name, width=Cm(width))
    c = txt(cell, [(caption, False)], size=8.5, align=WD_ALIGN_PARAGRAPH.CENTER,
            space_after=4)
    return c


def minitable(cell, rows, size=8.5, widths=None):
    """셀 안에 표를 넣는다."""
    t = cell.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            c = t.cell(i, j)
            c.text = ""
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.space_before = Pt(0)
            p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
            p.alignment = (WD_ALIGN_PARAGRAPH.LEFT if j == 0
                           else WD_ALIGN_PARAGRAPH.CENTER)
            setfont(p.add_run(str(v)), size, bold=(i == 0))
    if widths:
        for j, w in enumerate(widths):
            for r in t.rows:
                r.cells[j].width = Cm(w)
    # 표 뒤 여백
    para(cell).paragraph_format.space_after = Pt(3)
    return t

