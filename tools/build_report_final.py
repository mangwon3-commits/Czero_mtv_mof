def setfont(run, size=BODY, bold=False, italic=False):
    run.font.size = Pt(size); run.font.bold = bold; run.font.italic = italic
    run.font.name = FONT_EN
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)


def para(doc, text, size=BODY, bold=False, align=None, space_after=5,
         space_before=0, indent=None, italic=False):
    p = doc.add_paragraph(); pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    pf.space_after = Pt(space_after); pf.space_before = Pt(space_before)
    if indent is not None: pf.left_indent = Cm(indent)
    if align: p.alignment = align
    if text: setfont(p.add_run(text), size, bold, italic)
    return p


def rich(doc, chunks, size=BODY, space_after=5, indent=None):
    p = doc.add_paragraph(); pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    pf.space_after = Pt(space_after)
    if indent is not None: pf.left_indent = Cm(indent)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    for t, b in chunks: setfont(p.add_run(t), size, b)
    return p


def h1(doc, text):
    para(doc, text, size=12, bold=True, space_before=9, space_after=4)


def table(doc, rows, size=8.7, header=True, caption=None):
    if caption:
        para(doc, caption, size=8.7, bold=True, space_before=3, space_after=2)
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(rows):
        for j, cell in enumerate(row):
            c = t.cell(i, j); c.text = ""
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            p.paragraph_format.space_before = Pt(1)
            p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
            if j > 0: p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            setfont(p.add_run(str(cell)), size, bold=(header and i == 0))
    para(doc, "", size=3, space_after=2)
    return t


